-- Hibernate's old ddl-auto:update strategy created a unique constraint on
-- bookings.start_time at some point in the past. The current entity no longer
-- declares one, but ddl-auto never drops constraints it created, so it lingers
-- in already-running databases.
--
-- This constraint is stricter than the application's actual booking rule:
-- BookingService.reserveSlot() only blocks a slot when an active CONFIRMED or
-- still-valid RESERVED booking occupies it — cancelled/refunded/expired bookings
-- should free the slot for reuse. A hard DB-level unique constraint on start_time
-- prevents that and causes "duplicate key value violates unique constraint" (23505)
-- errors when rebooking a previously-used time slot.
--
-- The constraint name is auto-generated by Hibernate and can differ across
-- environments, so it's located dynamically by table + column instead of by name.
DO $$
DECLARE
    legacy_constraint text;
BEGIN
    SELECT con.conname INTO legacy_constraint
    FROM pg_constraint con
    JOIN pg_class rel ON rel.oid = con.conrelid
    JOIN pg_attribute att ON att.attrelid = con.conrelid AND att.attnum = con.conkey[1]
    WHERE rel.relname = 'bookings'
      AND con.contype = 'u'
      AND array_length(con.conkey, 1) = 1
      AND att.attname = 'start_time';

    IF legacy_constraint IS NOT NULL THEN
        EXECUTE format('ALTER TABLE bookings DROP CONSTRAINT %I', legacy_constraint);
    END IF;
END $$;
